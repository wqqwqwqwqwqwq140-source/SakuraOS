[bits 16]

find_mode:

    ; ES:SI = список VBE режимов

    mov ax, [mode_list_segment]
    mov es, ax

    mov si, [mode_list_offset]


.next_mode:

    ; CX = номер режима
    mov cx, [es:si]

    ; Конец списка
    cmp cx, 0xFFFF
    je .not_found


    ; Сохраняем номер режима
    push cx


    xor ax, ax
    mov es, ax

    mov di, mode_info

    mov ax, 0x4F01
    int 0x10

    pop cx
    cmp ax, 0x004F
    jne .next

    test word [mode_info], 1
    jz .next


    test word [mode_info], 0x80
    jz .next

    cmp word [mode_info + 0x12], 1920
    jne .next

    cmp word [mode_info + 0x14], 1080
    jne .next

    cmp byte [mode_info + 0x19], 32
    jne .next

    mov [vbe_mode], cx

    ; PhysBasePtr
    mov eax, [mode_info + 0x28]
    mov [framebuffer], eax

    ; BytesPerScanLine
    mov ax, [mode_info + 0x10]
    mov [pitch], ax

    clc
    ret


.next:

    ; Возвращаем ES:SI к списку режимов

    mov ax, [mode_list_segment]
    mov es, ax

    add si, 2

    jmp .next_mode


.not_found:

    stc
    ret



; Безсполезная фанкшен

print:

    mov ah, 0x0E
    cld

.print_loop:

    lodsb

    test al, al
    jz .done

    int 0x10

    jmp .print_loop

.done:
    ret



vbe_error:

    mov si, msg_vbe
    call print

    cli

.error_hang:
    hlt
    jmp .error_hang


gdt_start:

    dq 0

    ; 0x08 CODE
    ; Base  = 0
    ; Limit = 4 GB
    ; 32-bit

    dw 0xFFFF
    dw 0x0000
    db 0x00
    db 10011010b
    db 11001111b
    db 0x00
    ; 0x10 DATA
    ; Base  = 0
    ; Limit = 4 GB
    ; 32-bit

    dw 0xFFFF
    dw 0x0000
    db 0x00
    db 10010010b
    db 11001111b
    db 0x00


gdt_end:


gdt_descriptor:
    dw gdt_end - gdt_start - 1
    dd gdt_start

