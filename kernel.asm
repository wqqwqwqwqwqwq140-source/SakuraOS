[bits 16]
org 0x7E00

start:
    cli

    xor ax, ax
    mov ds, ax
    mov es, ax
    mov si, msg
    call print

    mov ax, 0x4F00
    mov di, vbe_info

    mov dword [es:di], 'VBE2'

    int 0x10

    cmp ax, 0x004F
    jne vbe_error

    mov si, [vbe_info + 0x0E]
    mov ax, [vbe_info + 0x10]

    mov [mode_list_offset], si
    mov [mode_list_segment], ax

    call find_mode

    jc vbe_error


    mov ax, 0x4F02

    mov bx, [vbe_mode]

    ; Bit 14 = Linear Framebuffer
    or bx, 0x4000

    int 0x10

    cmp ax, 0x004F
    jne vbe_error


    ; ==========================================
    ; красотища 1
    ; ==========================================



    in al, 0x92
    or al, 2
    out 0x92, al


    lgdt [gdt_descriptor]

    mov eax, cr0
    or eax, 1
    mov cr0, eax

    ; Far jump
    jmp 0x08:protected_mode_start

[bits 32]

protected_mode_start:

    ; Data selector = 0x10
    mov ax, 0x10

    mov ds, ax
    mov es, ax
    mov fs, ax
    mov gs, ax
    mov ss, ax

    ; Stack
    mov esp, 0x90000


    ; ==========================================
    ; Красивый комментарий 2))))
    ; ==========================================

    mov edi, [framebuffer]      
    mov eax, 0x00fff5ff
    mov ecx, 1920*1080
    rep stosd
.logo:
    mov esi, msg_OSname
    cld
    mov ecx, 0
    mov edi, [framebuffer]
    add edi, 888 * 4 + 1920 * 528 * 4
    push esi
    jmp .printlogo
.printlogo: ;хз зачем я пишу на коментарии здесь функшен тип чтобы печатать (мне лень комментировать, поэтому они раз в год)
    pop esi
    lodsb
    cmp al, 0
    je waitinput
    mov bl, al
    push esi
    mov esi, letter
    call print32
    sub edi, 1920*4*11-12*4
    jmp .printlogo
waitinput:
    in al, 0x64
    test al, 1
    jz waitinput
    mov edi, [framebuffer]      
    mov eax, 0x00fff5ff
    mov ecx, 1920*1080
    rep stosd
.testforclear:
    mov edi, command
    mov ecx, 255
    xor eax, eax
    rep stosb
    mov dword [cmd_len], 0
    mov byte  [shift_state], 0

    mov eax, [framebuffer]
    mov [cursor_pos], eax
    jmp .read_key
.read_key:
    in al, 0x64
    test al, 1
    jz .read_key

    in al, 0x60

    test al, 0x80
    jnz .key_up

    cmp al, 0x2A
    je .shift_on
    cmp al, 0x36
    je .shift_on
    cmp al, 0x1C
    je .enter
    cmp al, 0x0E
    je .backspace
    cmp al, 0x39
    je .space

    call scancode_to_ascii   
    jc .read_key

    call put_char
    jmp .read_key

.key_up:
    and al, 0x7F
    cmp al, 0x2A
    je .shift_off
    cmp al, 0x36
    je .shift_off
    jmp .read_key

.shift_on:
    mov byte [shift_state], 1
    jmp .read_key
.shift_off:
    mov byte [shift_state], 0
    jmp .read_key

.enter:
    ; сохраняем текущий X (столбец) курсора
    mov eax, [cursor_pos]
    sub eax, [framebuffer]
    xor edx, edx
    mov ecx, 1920*4
    div ecx
    
    xor edx, edx
    mov ecx, 12
    div ecx
    
    inc eax
    
    mov ecx, 1920*4*12
    mul ecx
    
    add eax, [framebuffer]
    mov [cursor_pos], eax
    pusha
    mov ecx, 7
    call .checkprefix
    popa

    cmp byte [is_system], 1
    je .do_system_command

    mov dword [cmd_len], 0
    jmp .read_key
.checkprefix:
    sub ecx, 1
    cmp ecx, 0
    je .systemcommand     
    mov al, [cmdsystem + ecx]
    cmp al, byte [command+ecx]
    jne .othercommands
    jmp .checkprefix
.othercommands:
    mov byte [is_system], 0
    ret
.systemcommand:
    mov byte [is_system], 1
    ret
.do_system_command:
    jmp hang

.backspace:
    mov eax, [cmd_len]
    test eax, eax
    jz .read_key
    dec eax
    mov [cmd_len], eax
    mov byte [command + eax], 0
    mov edi, [cursor_pos]
    sub edi, 12*4
    mov [cursor_pos], edi
    call erase_glyph
    jmp .read_key

.space:
    mov eax, [cmd_len]
    cmp eax, 254
    jae .read_key
    mov byte [command + eax], 32
    inc eax
    mov [cmd_len], eax
    mov edi, [cursor_pos]
    add edi, 12*4
    mov [cursor_pos], edi
    jmp .read_key
print32:
    lodsb
    cmp al, bl

    je .print32loop
    jmp print32
.print32loop:
    lodsb
    add edi, 4
    add ecx, 4
    cmp al, 0x00
    je .print32loop
    cmp al, 0x0b
    je .newline
    cmp al, 0x0f
    je .print32end
    push eax
    mov eax, [color]
    mov dword [edi], eax
    pop eax
    jmp .print32loop
.newline:
    add edi, 1920 * 4
    sub edi, ecx
    mov ecx, 0
    jmp .print32loop
.print32end:
    ret
scancode_to_ascii:
    push esi
    push ecx
    mov esi, ScanAsciiTable
    mov ecx, (ScanAsciiTableEnd - ScanAsciiTable) / 3
.loop:
    cmp byte [esi], al
    je .found
    add esi, 3
    loop .loop
    pop ecx
    pop esi
    stc
    ret
.found:
    cmp byte [shift_state], 0
    je .unshift
    mov al, [esi+2]
    jmp .done
.unshift:
    mov al, [esi+1]
.done:
    pop ecx
    pop esi
    clc
    ret

ascii_to_id:
    push esi
    push ecx
    mov esi, KeyTable
    mov ecx, (KeyTableEnd - KeyTable) / 2
.loop:
    cmp byte [esi+1], al
    je .found
    add esi, 2
    loop .loop
    pop ecx
    pop esi
    stc
    ret
.found:
    mov al, [esi]
    pop ecx
    pop esi
    clc
    ret

; ---------------------------------------------
; put_char: вход al = ASCII символа
; ---------------------------------------------
put_char:
    push ebx
    push eax             ; сохраняем оригинальный ASCII

    call ascii_to_id      ; al = id (если найден)
    jc .abort
    mov bl, al             ; bl = id для print32

    mov edi, [cmd_len]
    cmp edi, 254
    jae .draw
    mov eax, [esp]
    mov [command + edi], al
    inc edi
    mov [cmd_len], edi

.draw:
    xor ecx, ecx
    mov edi, [cursor_pos]
    push esi
    mov esi, letter
    call print32
    pop esi

    sub edi, 1920*4*11 + 4
    mov [cursor_pos], edi

.abort:
    pop eax
    pop ebx
    ret
erase_glyph:
    push eax
    push ecx
    push edi
    mov edi, [cursor_pos]
    mov ecx, 11
.row:
    push ecx
    mov ecx, 12
    mov eax, 0x00fff5ff
.col:
    mov [edi], eax
    add edi, 4
    loop .col
    pop ecx
    add edi, 1920*4 - 12*4
    loop .row
    pop edi
    pop ecx
    pop eax
    ret
hang:
    cli
    hlt
    jmp $
