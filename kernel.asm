[bits 16]
org 0x7E00

start:
    cli

    xor ax, ax
    mov ds, ax
    mov es, ax
    mov si, msg
    call print

    mov ax, 0x4F00
    mov di, vbe_info

    mov dword [es:di], 'VBE2'

    int 0x10

    cmp ax, 0x004F
    jne vbe_error

    mov si, [vbe_info + 0x0E]
    mov ax, [vbe_info + 0x10]

    mov [mode_list_offset], si
    mov [mode_list_segment], ax

    call find_mode

    jc vbe_error


    mov ax, 0x4F02

    mov bx, [vbe_mode]

    ; Bit 14 = Linear Framebuffer
    or bx, 0x4000

    int 0x10

    cmp ax, 0x004F
    jne vbe_error


    ; ==========================================
    ; красотища 1
    ; ==========================================



    in al, 0x92
    or al, 2
    out 0x92, al


    lgdt [gdt_descriptor]

    mov eax, cr0
    or eax, 1
    mov cr0, eax

    ; Far jump
    jmp 0x08:protected_mode_start

[bits 32]

protected_mode_start:

    ; Data selector = 0x10
    mov ax, 0x10

    mov ds, ax
    mov es, ax
    mov fs, ax
    mov gs, ax
    mov ss, ax

    ; Stack
    mov esp, 0x90000


    ; ==========================================
    ; Красивый комментарий 2))))
    ; ==========================================

    mov edi, [framebuffer]      
    mov eax, 0x00fff5ff
    mov ecx, 1920*1080
    rep stosd
.logo:
    mov esi, msg_OSname
    cld
    mov ecx, 0
    mov edi, [framebuffer]
    add edi, 888 * 4 + 1920 * 528 * 4
    push esi
    jmp .printlogo
.printlogo: ;хз зачем я пишу на коментарии здесь функшен тип чтобы печатать (мне лень комментировать, поэтому они раз в год)
    pop esi
    lodsb
    cmp al, 0
    je .waitinput
    mov bl, al
    push esi
    mov esi, letter
    call print32
    sub edi, 1920*4*11-12*4
    jmp .printlogo
.waitinput:
    in al, 0x64
    test al, 1
    jz .waitinput
    mov edi, [framebuffer]      
    mov eax, 0x00fff5ff
    mov ecx, 1920*1080
    rep stosd
    cld
    jmp hang

print32:
    lodsb
    cmp al, bl

    je .print32loop
    jmp print32
.print32loop:
    lodsb
    add edi, 4
    add ecx, 4
    cmp al, 0x00
    je .print32loop
    cmp al, 0x0b
    je .newline
    cmp al, 0x0f
    je .print32end
    mov dword [edi], 0x00ff1fff

    jmp .print32loop
.newline:
    add edi, 1920 * 4
    sub edi, ecx
    mov ecx, 0
    jmp .print32loop
.print32end:
    ret
hang:
    cli
    hlt
    jmp $
